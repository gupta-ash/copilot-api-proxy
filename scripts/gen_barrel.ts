/**
 * gen_barrel.ts — build-time generator for `src/lib/transform/index.ts`
 * (per M3, X13).
 *
 * **Why this exists.** Every body-engine + stream-event-engine rule
 * self-registers via `registry.register()` at module load. The engine
 * needs SOMEONE to import each rule file at least once so the
 * side-effect import fires. The barrel `index.ts` does exactly that:
 * one `import "./X.ts"` per rule file, importing for side-effect only.
 *
 * **Why generated.** Hand-maintained barrels drift the moment a rule is
 * added without remembering the index update — the rule then silently
 * never runs (the registry doesn't know it). The
 * `tests/transform/barrel.test.ts` test catches drift, but generating
 * the file makes drift impossible by construction.
 *
 * **Output contract (idempotent).**
 *   - Sorted alphabetical for diff stability.
 *   - One side-effect import per file (no re-export — the rules are not
 *     consumed by name from the barrel; they register themselves).
 *   - Banner comment marks the file as auto-generated.
 *
 * **Engine-core skip-list.** The set below names every engine-core file
 * that lives in `src/lib/transform/` but is NOT a rule (it's the engine
 * scaffolding). New rule files just need to NOT match the skip-list.
 *
 * **Wired via `package.json` `prebuild` script** (alongside
 * `gen_version.ts`). Re-runs on every `bun run build`. Manual run:
 * `bun run scripts/gen_barrel.ts`.
 *
 * **Stdlib only.** No deps; works on bun and node.
 */

import { readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");
const TRANSFORM_DIR = resolve(repoRoot, "src/lib/transform");

const ENGINE_CORE = new Set<string>([
  "types.ts",
  "registry.ts",
  "predicate.ts",
  "apply.ts",
  "apply_event.ts",
  "lint.ts",
  "version.ts",
  "index.ts",
  // M7b — stream-event scaffolding (concrete StreamState shape +
  // per-stream lifecycle Map). Pure data/lifecycle module, NOT a
  // registered rule — translators register, sse-state does not.
  "sse-state.ts",
  // M8 — shared usage-shape helper extracted from the M7b translator
  // (D-LOCK-2). Pure pure-function module, NOT a registered rule —
  // consumers (M7b translator + future M5 non-stream path + M9/M10
  // fixture replay) import directly.
  "usage.ts",
  // M9 — public-API surface for drop-in plugin authors (D-LOCK-6).
  // Pure re-export module of the LOCKED set of names from registry/
  // types/headers; NOT a registered rule. Plugin authors import from
  // `~/lib/transform/plugin` instead of the internal modules.
  "plugin.ts",
  // M9 — drop-in code lazy-loader (D-LOCK-5 + D-LOCK-15). Boot-time
  // helper that enumerates `${transforms.custom_dir}/*.ts` and
  // dynamic-imports each so its `register()` side effect fires. Called
  // from main.ts; NOT a registered rule itself.
  "custom-loader.ts",
]);

function isRuleFile(name: string): boolean {
  if (!name.endsWith(".ts")) return false;
  if (name.startsWith("_")) return false; // private modules
  if (ENGINE_CORE.has(name)) return false;
  return true;
}

const ruleFiles = readdirSync(TRANSFORM_DIR)
  .filter(isRuleFile)
  .sort((a, b) => a.localeCompare(b));

const lines = [
  "// AUTO-GENERATED by scripts/gen_barrel.ts. DO NOT EDIT.",
  "// Side-effect imports register every rule into the body or stream_event registry.",
  "// Regenerate: bun run scripts/gen_barrel.ts (also runs via `bun run prebuild`).",
  "",
  ...ruleFiles.map((f) => `import "./${f}";`),
  "",
];

const outPath = resolve(TRANSFORM_DIR, "index.ts");
writeFileSync(outPath, lines.join("\n"), "utf-8");

// eslint-disable-next-line no-console
console.log(`gen_barrel: wrote ${outPath} (${ruleFiles.length} rules)`);
