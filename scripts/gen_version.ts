/**
 * gen_version.ts — generates `src/lib/transform/version.ts` at build time
 * (per F3/M2.5).
 *
 * **Why this exists.** Importing the entire `package.json` at runtime via
 * `import pkg from "../../../package.json" with { type: "json" }` makes
 * tsdown inline the WHOLE JSON document into `dist/main.js` — every dep,
 * script, description, etc. (~2KB minified bloat that NEVER gets read at
 * runtime). Generating a 1-line constant from `package.json.version`
 * sidesteps the bloat AND the JSON-import-at-bundle-time fragility.
 *
 * **Wired via `package.json` `prebuild` script.** `bun run build` runs
 * `prebuild` first (bun convention), which invokes this generator. The
 * generated `version.ts` is gitignored so it never drifts from
 * `package.json`. Run `bun run prebuild` (or just `bun run build`) to
 * regenerate; the file is also committed-once as a side-effect of dev
 * `bun test` runs through this same script (run it manually once after
 * checkout if you skipped a build).
 *
 * **Stdlib only.** No deps; works on bun and node alike.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");
const pkgPath = resolve(repoRoot, "package.json");
const outPath = resolve(repoRoot, "src/lib/transform/version.ts");

interface PkgShape {
  version: string;
}
const pkg = JSON.parse(readFileSync(pkgPath, "utf8")) as PkgShape;

if (typeof pkg.version !== "string" || pkg.version.length === 0) {
  throw new Error(
    `gen_version: package.json.version must be a non-empty string (got ${JSON.stringify(pkg.version)})`,
  );
}

const banner =
  "// AUTO-GENERATED by scripts/gen_version.ts — do not edit; regenerated on every build.\n";
const body = `export const ENGINE_VERSION = ${JSON.stringify(pkg.version)} as const;\n`;
writeFileSync(outPath, banner + body, "utf8");

// eslint-disable-next-line no-console
console.log(`gen_version: wrote ${outPath} (version ${pkg.version})`);
