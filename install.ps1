#requires -Version 5.1
# Download this committed script from the selected Release; never pipe it into iex.
[CmdletBinding()]
param(
    [Parameter(Mandatory=$true)][string]$Version,
    [Parameter(Mandatory=$true)][string]$WorkRoot,
    [ValidateSet('Check','Install','Verify')][string]$Mode = 'Install',
    [string]$UserRoot = '', [string]$InstallRoot = '', [string]$NodeExe = '',
    [ValidateRange(1,65535)][int]$Port,
    [switch]$AdoptExisting, [switch]$Activate
)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
# Resolve builtins from this host, not an inherited PowerShell 7-first module path.
# No caller/global PSModulePath or profile changes are made.
foreach ($module in @('Microsoft.PowerShell.Management','Microsoft.PowerShell.Utility','Microsoft.PowerShell.Security')) {
    Import-Module -Name ($PSHOME+'/Modules/'+$module+'/'+$module+'.psd1') -Scope Local -ErrorAction Stop
}
$repository = 'gupta-ash/copilot-api-proxy'
function Full-Path([string]$Path) {
    if (-not [IO.Path]::IsPathRooted($Path) -or $Path -notmatch '^[A-Za-z]:[\\/]' -or $Path -match '[*?]' -or $Path -match '(^|[\\/])\.\.([\\/]|$)') { throw 'A local absolute path without traversal is required.' }
    return [IO.Path]::GetFullPath($Path).TrimEnd('\','/')
}
function Unlinked([string]$Path) {
    for ($p = (Full-Path $Path); $p; $p = Split-Path -Parent $p) {
        $item = Get-Item -LiteralPath $p -Force -ErrorAction SilentlyContinue
        if ($item -and ($item.Attributes -band [IO.FileAttributes]::ReparsePoint)) { throw "Linked path refused: $p" }
    }
}
function Overlaps([string]$A, [string]$B) { return $A -ieq $B -or $A.StartsWith($B+'\',[StringComparison]::OrdinalIgnoreCase) -or $B.StartsWith($A+'\',[StringComparison]::OrdinalIgnoreCase) }
function Hash([string]$Path) { return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToLowerInvariant() }
function Api([string]$Suffix) { return Invoke-RestMethod -Uri ('https://api.github.com/repos/'+$repository+'/'+$Suffix) -Headers @{Accept='application/vnd.github+json';'User-Agent'='copilot-api-proxy-installer'} }
function Bytes-Digest([byte[]]$Bytes, [ValidateSet('SHA1','SHA256')][string]$Algorithm='SHA256') {
    $hasher=[Security.Cryptography.HashAlgorithm]::Create($Algorithm)
    try { return [BitConverter]::ToString($hasher.ComputeHash($Bytes)).Replace('-','').ToLowerInvariant() }
    finally { $hasher.Dispose() }
}
function Git-BlobDigest([byte[]]$Bytes) {
    $header=[Text.Encoding]::ASCII.GetBytes(('blob '+$Bytes.Length+[char]0))
    $hasher=[Security.Cryptography.SHA1]::Create()
    try {
        [void]$hasher.TransformBlock($header,0,$header.Length,$header,0)
        [void]$hasher.TransformFinalBlock($Bytes,0,$Bytes.Length)
        return [BitConverter]::ToString($hasher.Hash).Replace('-','').ToLowerInvariant()
    } finally { $hasher.Dispose() }
}
function Closed-Fields($Object,[string[]]$Names) {
    if ($null -eq $Object -or $Object -is [array] -or $Object -is [string]) { throw 'Expected a closed release object.' }
    $actual=@($Object.PSObject.Properties.Name)
    if ($actual.Count -ne $Names.Count) { throw 'Unexpected release object fields.' }
    foreach ($name in $Names) { if ($actual -cnotcontains $name) { throw ('Missing release field: '+$name) } }
}
function Source-Release([string]$Commit) {
    # The mutable Release receipt binds generated bytes, not source authority.
    # Establish the committed static closure before reading/executing its backend.
    $commitObject=Api ('git/commits/'+$Commit)
    if ($commitObject.sha -cne $Commit -or $commitObject.tree.sha -cnotmatch '^[0-9a-f]{40}$') { throw 'Committed source tree identity mismatch.' }
    $tree=Api ('git/trees/'+$commitObject.tree.sha+'?recursive=1')
    if ($tree.sha -cne $commitObject.tree.sha -or $tree.truncated -isnot [bool] -or $tree.truncated -or $tree.tree -isnot [array]) { throw 'Incomplete/unbound committed source tree.' }
    $entries=@{}
    foreach ($entry in $tree.tree) {
        if ($entry.path -isnot [string] -or -not $entry.path -or $entries.ContainsKey($entry.path) -or $entry.sha -cnotmatch '^[0-9a-f]{40}$' -or $entry.mode -cnotin @('040000','100644','100755') -or (($entry.mode -ceq '040000') -ne ($entry.type -ceq 'tree')) -or ($entry.mode -cne '040000' -and $entry.type -cne 'blob')) { throw 'Unsafe/duplicate committed source tree entry.' }
        $entries[$entry.path]=$entry
    }
    foreach ($name in @('install.ps1','deploy/release-files.json')) {
        if (-not $entries.ContainsKey($name) -or $entries[$name].path -cne $name -or $entries[$name].type -cne 'blob') { throw 'Missing committed installer/declaration.' }
    }
    $content=Api ('contents/deploy/release-files.json?ref='+$Commit)
    if ($content.type -cne 'file' -or $content.path -cne 'deploy/release-files.json' -or $content.encoding -cne 'base64' -or $content.sha -cne $entries['deploy/release-files.json'].sha) { throw 'Committed release declaration identity mismatch.' }
    $bytes=[Convert]::FromBase64String($content.content)
    if ((Git-BlobDigest $bytes) -cne $content.sha) { throw 'Committed declaration bytes do not match its Git object.' }
    $declaration=[Text.Encoding]::UTF8.GetString($bytes) | ConvertFrom-Json
    Closed-Fields $declaration @('schema_version','component','files','retired_files','generated_trees','generated_files')
    if ($declaration.schema_version -ne 1 -or $declaration.component -cne 'copilot-proxy' -or ($declaration.generated_trees -join ',') -cne 'dist,node_modules' -or ($declaration.generated_files -join ',') -cne 'VERSION.txt' -or $declaration.files -isnot [array] -or $declaration.retired_files -isnot [array]) { throw 'Unsupported committed release declaration.' }
    $expected=@{}
    foreach ($name in @('install.ps1','deploy/release-files.json','LICENSE','NOTICE','config/default.yaml','package.json','bun.lock')) { $expected[$name]=$name }
    $operators=@('install_bundle.ps1','install_local.ps1','install_service.ps1','uninstall_service.ps1')
    foreach ($name in @('start_proxy','start_proxy_no_rollback','stop_proxy','status_proxy','proxy_log_on','proxy_log_off')) { $operators += ($name+'.ps1'),($name+'.sh') }
    foreach ($name in $operators) { $expected['deploy/'+$name]='scripts/'+$name }
    if ($declaration.files.Count -ne $expected.Count) { throw 'Incomplete/unexpected committed static closure.' }
    $destinations=@{}; $sources=@{}
    foreach ($row in $declaration.files) {
        Closed-Fields $row @('source','destination')
        if ($row.source -isnot [string] -or @($expected.Keys) -cnotcontains $row.source -or $row.destination -cne $expected[$row.source] -or $sources.ContainsKey($row.source) -or $destinations.ContainsKey($row.destination) -or -not $entries.ContainsKey($row.source) -or $entries[$row.source].path -cne $row.source -or $entries[$row.source].type -cne 'blob') { throw 'Invalid/missing committed static source mapping.' }
        $mode=if ($row.destination.EndsWith('.sh',[StringComparison]::Ordinal)) { '100755' } else { $entries[$row.source].mode }
        $sources[$row.source]=$true; $destinations[$row.destination]=[pscustomobject]@{sha=$entries[$row.source].sha;mode=$mode}
    }
    return [pscustomobject]@{declaration=$declaration;declaration_sha256=(Bytes-Digest $bytes);destinations=$destinations}
}
function Admit-ReleasePayload($Zip,$Rows,$Envelope,$Source,[string]$Commit,[string]$Tag) {
    if ($Envelope.declaration_sha256 -cne $Source.declaration_sha256 -or -not $Rows.ContainsKey('deploy/release-files.json') -or $Rows['deploy/release-files.json'].sha256 -cne $Source.declaration_sha256) { throw 'Packaged declaration differs from committed source.' }
    $static=$Source.destinations
    foreach ($name in $static.Keys) { if (-not $Rows.ContainsKey($name) -or $Rows[$name].path -cne $name -or $Rows[$name].mode -cne $static[$name].mode) { throw ('Incomplete/static source mode mismatch: '+$name) } }
    $entries=@{}; foreach ($entry in $Zip.Entries) { $entries[$entry.FullName]=$entry }
    foreach ($name in $Rows.Keys) {
        if ($static.ContainsKey($name)) {
            $stream=$entries[$name].Open(); $memory=[IO.MemoryStream]::new()
            try { $stream.CopyTo($memory); $digest=Git-BlobDigest $memory.ToArray() } finally { $stream.Dispose(); $memory.Dispose() }
            if ($digest -cne $static[$name].sha) { throw ('Static package bytes differ from committed source: '+$name) }
        } elseif ($name -ceq 'VERSION.txt') {
            if ($Rows[$name].mode -cne '100644') { throw 'Invalid generated marker mode.' }
            $reader=[IO.StreamReader]::new($entries[$name].Open())
            try { $marker=$reader.ReadToEnd() } finally { $reader.Dispose() }
            if ($marker -cne "version=$Tag`nsource_commit=$Commit`ndirty=False`n") { throw 'Generated version/source marker mismatch.' }
        } elseif ($name.StartsWith('dist/',[StringComparison]::Ordinal)) {
            # tsdown emits the entry, ESM chunks/maps and mapless facade chunks.
            # Hashes remain bound to the selected archive receipt; no operators,
            # binaries, nested trees or unpaired maps can enter via this lane.
            if ($name -cnotmatch '^dist/[A-Za-z0-9_-]+\.js(?:\.map)?$' -or ($name.EndsWith('.map',[StringComparison]::Ordinal) -and $Rows[$name].mode -cne '100644') -or ($name.EndsWith('.js',[StringComparison]::Ordinal) -and $Rows[$name].mode -cnotin @('100644','100755'))) { throw ('Unexpected generated dist member: '+$name) }
            if ($name.EndsWith('.map',[StringComparison]::Ordinal)) {
                $pair=$name.Substring(0,$name.Length-4)
                if (-not $Rows.ContainsKey($pair) -or $Rows[$pair].path -cne $pair) { throw ('Incomplete generated dist/map pair: '+$name) }
            }
        } elseif (-not $name.StartsWith('node_modules/',[StringComparison]::Ordinal)) { throw ('Unexpected release member: '+$name) }
    }
    foreach ($name in @('VERSION.txt','dist/main.js','dist/main.js.map')) { if (-not $Rows.ContainsKey($name) -or $Rows[$name].path -cne $name) { throw ('Incomplete generated release: '+$name) } }
    if ($Rows['dist/main.js'].mode -cne '100755' -or -not @($Rows.Keys | Where-Object { $_.StartsWith('node_modules/hono/',[StringComparison]::Ordinal) }).Count) { throw 'Missing generated entrypoint/production dependency closure.' }
    $retired=@{}
    foreach ($name in $Source.declaration.retired_files) {
        if ($name -isnot [string] -or $name -cnotmatch '^(?:(?:dist|node_modules|scripts|config)/[A-Za-z0-9_@.()+,= /-]+|install\.ps1|deploy/release-files\.json|LICENSE|NOTICE|package\.json|bun\.lock|VERSION\.txt)$' -or $name -match '(^|/)\.{1,2}(/|$)|//|[. ](/|$)|/$' -or $retired.ContainsKey($name) -or $Rows.ContainsKey($name)) { throw 'Invalid/live committed retirement.' }
        $retired[$name]=$true
    }
}
try {
    if ($Version -cnotmatch '^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$' -or $Version -ieq 'latest') { throw 'Version must be an exact release tag, not latest.' }
    $actualHome = [Environment]::GetFolderPath([Environment+SpecialFolder]::UserProfile)
    if (-not $UserRoot) { $UserRoot = $actualHome }
    $UserRoot = Full-Path $UserRoot
    if ($UserRoot -ine (Full-Path $actualHome)) { throw 'UserRoot must be the invoking account profile.' }
    $WorkRoot = Full-Path $WorkRoot
    Unlinked $UserRoot; Unlinked $WorkRoot
    $metadata = Join-Path $UserRoot '.agents/installations/copilot-api-proxy'
    $installedPath = Join-Path $metadata 'installed.json'
    Unlinked $installedPath
    $prior = if (Test-Path -LiteralPath $installedPath -PathType Leaf) { Get-Content -LiteralPath $installedPath -Raw | ConvertFrom-Json } else { $null }
    $selectedRoot = $InstallRoot
    if (-not $selectedRoot -and $prior) { $selectedRoot = [string]$prior.parameters.InstallRoot }
    if (-not $selectedRoot) {
        $record = Join-Path $UserRoot '.local/share/copilot-proxy/install-dir.txt'
        Unlinked $record
        if (Test-Path -LiteralPath $record -PathType Leaf) { $selectedRoot = [IO.File]::ReadAllText($record).Trim() }
        else { $selectedRoot = Join-Path $UserRoot '.agents/services/copilot-proxy' }
    }
    $selectedRoot = Full-Path $selectedRoot
    $protectedRoots=@($selectedRoot,(Full-Path (Join-Path $UserRoot '.local/share/copilot-proxy')),(Full-Path $metadata))
    if (Test-Path -LiteralPath (Join-Path $PSScriptRoot '.git')) { $protectedRoots += (Full-Path $PSScriptRoot) }
    foreach ($protected in $protectedRoots) {
        if (Overlaps $WorkRoot $protected) { throw 'WorkRoot must be outside source, installation and private state roots.' }
    }
    if (-not (Test-Path -LiteralPath $WorkRoot -PathType Container)) { throw 'WorkRoot must already exist and be owned by this account.' }
    $drive=[IO.DriveInfo]::new([IO.Path]::GetPathRoot($WorkRoot))
    if (-not $drive.IsReady -or $drive.DriveType -notin @([IO.DriveType]::Fixed,[IO.DriveType]::Removable,[IO.DriveType]::Ram)) { throw 'WorkRoot must be available local storage, not a mapped network drive.' }
    $sid = [Security.Principal.WindowsIdentity]::GetCurrent().User.Value
    $owner = (Get-Acl -LiteralPath $WorkRoot).GetOwner([Security.Principal.SecurityIdentifier]).Value
    if ($owner -cne $sid) { throw 'WorkRoot is not owned by the invoking account.' }
    if (Test-Path -LiteralPath $metadata -PathType Container) {
        if ((Get-Acl -LiteralPath $metadata).GetOwner([Security.Principal.SecurityIdentifier]).Value -cne $sid) { throw 'Retained installation metadata is not owned by the invoking account.' }
    }
    if ($Mode -eq 'Verify') {
        if (-not $prior) { throw 'Missing retained installation receipt; Verify never downloads or repairs.' }
        if ($AdoptExisting -or $Activate) { throw 'Verify is read-only and refuses adoption/activation.' }
        $backend = Join-Path $metadata 'install_local.ps1'
        Unlinked $backend
        $binding = @($prior.files | Where-Object { $_.path -ceq $backend })
        if ($binding.Count -ne 1 -or (Hash $backend) -cne $binding[0].sha256) { throw 'Retained verifier is missing or changed.' }
        $frontdoorBinding=@($prior.files | Where-Object { $_.path -ceq (Join-Path $metadata 'install.ps1') })
        if ($frontdoorBinding.Count -ne 1 -or (Hash $PSCommandPath) -cne $frontdoorBinding[0].sha256) { throw 'Executing frontdoor differs from the retained installed release.' }
        $backendArgs = @{}; foreach ($key in $PSBoundParameters.Keys) { $backendArgs[$key] = $PSBoundParameters[$key] }
        $backendArgs.UserRoot = $UserRoot; $backendArgs.WorkRoot = $WorkRoot
        & $backend @backendArgs
        if ($LASTEXITCODE -ne 0) { throw 'Offline verification failed.' }
        exit 0
    }
    # Child downloads, extraction, caches and temporary files remain in WorkRoot.
    $operation = Join-Path $WorkRoot ('operation-'+[guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Path $operation | Out-Null
    foreach ($key in @('TEMP','TMP','TMPDIR','CLAUDE_CODE_TMPDIR','npm_config_cache','BUN_INSTALL_CACHE_DIR')) { [Environment]::SetEnvironmentVariable($key,$operation,'Process') }
    [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
    $escaped = [Uri]::EscapeDataString($Version)
    $release = Api ('releases/tags/'+$escaped)
    if ($release.tag_name -cne $Version -or $release.draft) { throw 'Release tag identity/state mismatch.' }
    $reference = Api ('git/ref/tags/'+$escaped)
    if ($reference.ref -cne ('refs/tags/'+$Version)) { throw 'Tag reference mismatch.' }
    $target = $reference.object; $seen = @{}
    while ($target.type -cne 'commit') {
        if ($target.type -cne 'tag' -or $target.sha -cnotmatch '^[0-9a-f]{40}$' -or $seen.ContainsKey($target.sha)) { throw 'Invalid/cyclic annotated tag.' }
        $seen[$target.sha] = $true; $tag = Api ('git/tags/'+$target.sha)
        if ($tag.sha -cne $target.sha) { throw 'Annotated tag identity mismatch.' }; $target = $tag.object
    }
    if ($target.sha -cnotmatch '^[0-9a-f]{40}$') { throw 'Tag must resolve to a full commit OID.' }
    $committedFrontdoor=Api ('contents/install.ps1?ref='+$target.sha)
    if ($committedFrontdoor.type -cne 'file' -or $committedFrontdoor.path -cne 'install.ps1' -or $committedFrontdoor.encoding -cne 'base64' -or $committedFrontdoor.sha -cnotmatch '^[0-9a-f]{40}$') { throw 'Cannot bind the committed release frontdoor.' }
    $sourceBytes=[Convert]::FromBase64String($committedFrontdoor.content)
    $sourceHasher=[Security.Cryptography.SHA256]::Create()
    try { $sourceDigest=[BitConverter]::ToString($sourceHasher.ComputeHash($sourceBytes)).Replace('-','').ToLowerInvariant() } finally { $sourceHasher.Dispose() }
    if ((Hash $PSCommandPath) -cne $sourceDigest) { throw 'Executing frontdoor differs from the selected commit. Download that release script explicitly.' }
    $sourceRelease=Source-Release $target.sha
    if ((Git-BlobDigest $sourceBytes) -cne $sourceRelease.destinations['install.ps1'].sha) { throw 'Executing frontdoor is not in the selected commit tree.' }
    if ($prior -and $prior.source_commit -cne $target.sha) {
        if ($prior.source_commit -cnotmatch '^[0-9a-f]{40}$') { throw 'Invalid retained source OID.' }
        $comparison=Api ('compare/'+$prior.source_commit+'...'+$target.sha)
        if ($comparison.status -cne 'ahead' -or $comparison.base_commit.sha -cne $prior.source_commit) { throw 'Downgrade/divergent source refused; upgrades must descend from the retained installed source.' }
    }
    $assetName = 'copilot-proxy-'+$Version+'.zip'
    foreach ($name in @($assetName,($assetName+'.json'),'install.ps1')) {
        $asset = @($release.assets | Where-Object { $_.name -ceq $name })
        if ($asset.Count -ne 1 -or $asset[0].browser_download_url -cne ('https://github.com/'+$repository+'/releases/download/'+$escaped+'/'+$name)) { throw "Missing/ambiguous release asset: $name" }
        Invoke-WebRequest -UseBasicParsing -Uri $asset[0].browser_download_url -OutFile (Join-Path $operation $name) | Out-Null
    }
    $envelopePath = Join-Path $operation ($assetName+'.json')
    $envelope = Get-Content -LiteralPath $envelopePath -Raw | ConvertFrom-Json
    Closed-Fields $envelope @('schema_version','component','source_repository','source_commit','tag','version','declaration_sha256','asset','asset_sha256','built_utc','payload')
    if ($envelope.payload -isnot [array] -or $envelope.declaration_sha256 -cnotmatch '^[0-9a-f]{64}$') { throw 'Incomplete release receipt/payload declaration.' }
    $archive = Join-Path $operation $assetName
    if ($envelope.schema_version -ne 1 -or $envelope.component -cne 'copilot-proxy' -or $envelope.source_repository -cne $repository -or $envelope.tag -cne $Version -or $envelope.version -cne $Version -or $envelope.source_commit -cne $target.sha -or $envelope.asset -cne $assetName -or $envelope.asset_sha256 -cnotmatch '^[0-9a-f]{64}$' -or (Hash $archive) -cne $envelope.asset_sha256) { throw 'Release receipt/tag/OID/archive digest mismatch.' }
    Add-Type -AssemblyName @('System.IO.Compression','System.IO.Compression.FileSystem')
    $zip = [IO.Compression.ZipFile]::OpenRead($archive)
    $bundle = Join-Path $operation 'payload'
    try {
        $rows = @{}; foreach ($row in $envelope.payload) {
            Closed-Fields $row @('path','sha256','mode')
            if ($row.path -isnot [string] -or $row.sha256 -isnot [string] -or $row.mode -isnot [string]) { throw 'Release payload fields must be strings.' }
            $name = [string]$row.path
            if ($name -cnotmatch '^[A-Za-z0-9_@.()+,= -]+(/[A-Za-z0-9_@.()+,= -]+)*$' -or @($name.Split('/') | Where-Object { $_ -in @('.','..') -or $_ -match '[. ]$|^(?i:con|prn|aux|nul|com[1-9]|lpt[1-9])(\.|$)' }).Count -or $rows.ContainsKey($name) -or $row.sha256 -cnotmatch '^[0-9a-f]{64}$' -or $row.mode -cnotin @('100644','100755')) { throw 'Unsafe/duplicate release member declaration.' }
            $rows[$name] = $row
        }
        if ($rows.Count -ne $zip.Entries.Count) { throw 'ZIP member count mismatch.' }
        $members = @{}
        foreach ($entry in $zip.Entries) {
            $name = $entry.FullName
            if ($name.Contains('\') -or -not $rows.ContainsKey($name) -or $rows[$name].path -cne $name -or $members.ContainsKey($name)) { throw 'ZIP has an extra, duplicate or unnormalized member.' }
            $members[$name] = $true
            $unix = ($entry.ExternalAttributes -shr 16) -band 65535
            $expectedBits=if ($rows[$name].mode -ceq '100755') { 33261 } else { 33188 }
            if (($entry.ExternalAttributes -band [int][IO.FileAttributes]::ReparsePoint) -ne 0 -or $unix -ne $expectedBits) { throw 'ZIP member type/mode mismatch (links are forbidden).' }
            $stream = $entry.Open(); $sha = [Security.Cryptography.SHA256]::Create()
            try { $digest = [BitConverter]::ToString($sha.ComputeHash($stream)).Replace('-','').ToLowerInvariant() } finally { $stream.Dispose(); $sha.Dispose() }
            if ($digest -cne $rows[$name].sha256) { throw "ZIP member digest mismatch: $name" }
        }
        Admit-ReleasePayload $zip $rows $envelope $sourceRelease $target.sha $Version
        if ($sourceDigest -cne $rows['install.ps1'].sha256 -or (Hash (Join-Path $operation 'install.ps1')) -cne $rows['install.ps1'].sha256) { throw 'Executing/committed frontdoor differs from this release. Download its install.ps1 and invoke that script explicitly.' }
        [IO.Compression.ZipFile]::ExtractToDirectory($archive,$bundle)
    } finally { $zip.Dispose() }
    $backendArgs = @{}; foreach ($key in $PSBoundParameters.Keys) { $backendArgs[$key] = $PSBoundParameters[$key] }
    $backendArgs.UserRoot=$UserRoot; $backendArgs.WorkRoot=$WorkRoot; $backendArgs.InstallRoot=$selectedRoot
    $backendArgs.PackageReceipt=$envelopePath; $backendArgs.ArchivePath=$archive; $backendArgs.Frontdoor=$PSCommandPath
    & (Join-Path $bundle 'scripts/install_bundle.ps1') @backendArgs -NoStop -NoStart -SkipAutostart
    if ($LASTEXITCODE -ne 0) { throw 'Local installation failed; retain WorkRoot diagnostics/backups. No automatic rollback was attempted.' }
    exit 0
} catch { Write-Error $_ -ErrorAction Continue; exit 1 }
